def classify_kind(title: str, category: str | None = None) -> str:
    """'admin'(단순 행정 안내) 또는 'activity'(활동·기회). 규칙 기반, 토큰 0."""
    t = (title or "").lower()
    if any(k in t for k in STRONG_ADMIN) and not re.search(r"모집|공모|대회|참가자|선발", t):
        return "admin"
    act = any(k in t for k in ACTIVITY_KEYWORDS)
    adm = any(k in t for k in ADMIN_KEYWORDS)
    if category in ("비교과", "취업", "장학"):
        act = True
    if adm and not act:
        return "admin"
    if act:
        return "activity"
    # 둘 다 아니면: 학사·기타 게시판의 일반 안내는 행정, 나머지는 활동으로 둔다
    if category in ("학사", "기타") or re.search(r"(안내|공지|알림)\s*$", t) and not re.search(r"(신청|접수)", t):
        return "admin"
    return "activity"


